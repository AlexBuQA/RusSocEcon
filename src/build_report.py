def h(text, level=1):
    doc.add_heading(text, level=level)


def p(text, bold=False, italic=False):
    par = doc.add_paragraph()
    run = par.add_run(text)
    par.paragraph_format.first_line_indent = Cm(1.25)
    par.paragraph_format.space_after = Pt(6)
    if bold:
        run.bold = True
    if italic:
        run.italic = True
    return par


def bullet(text):
    par = doc.add_paragraph(text, style='List Bullet')
    par.paragraph_format.space_after = Pt(2)


def numbered(text):
    par = doc.add_paragraph(text, style='List Number')
    par.paragraph_format.space_after = Pt(2)


def fig(path, caption, width=16):
    doc.add_picture(str(path), width=Cm(width))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap = doc.add_paragraph(caption)
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for run in cap.runs:
        run.italic = True
        run.font.size = Pt(10)


def table_from_csv(path, caption, formats=None, max_rows=None):
    df = pd.read_csv(path)
    if max_rows:
        df = df.head(max_rows)
    cap = doc.add_paragraph(caption)
    for run in cap.runs:
        run.bold = True
        run.font.size = Pt(11)
    t = doc.add_table(rows=1, cols=len(df.columns))
    t.style = 'Light Grid Accent 1'
    for j, col in enumerate(df.columns):
        t.rows[0].cells[j].text = str(col)
    for _, row in df.iterrows():
        cells = t.add_row().cells
        for j, col in enumerate(df.columns):
            v = row[col]
            if formats and col in formats and pd.notna(v):
                v = formats[col].format(v)
            cells[j].text = str(v)
    doc.add_paragraph()


def rub(x):
    return f'{x:,.0f}'.replace(',', ' ')


